use crate::day_10;

pub fn print_success_message(score: u32) {
    println!("The total syntax error score is {}.", score);
}

pub fn get_total_syntax_error_score(lines: &[Vec<char>]) -> u32 {
    lines.iter().map(|line| get_syntax_error_score(&line)).sum()
}

fn get_syntax_error_score(line: &[char]) -> u32 {
    if let Some((&first, rest)) = line.split_first() {
        match day_10::parse(first, rest, vec![]) {
            Ok(_) => 0,
            Err(score) => score,
        }
    } else {
        0
    }
}

